if REPORTLAB_AVAILABLE:
    class NumberedCanvas(canvas.Canvas):
        """Two-pass canvas for dynamic total page number in footer."""
        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            self._saved_page_states = []

        def showPage(self):
            self._saved_page_states.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            num_pages = len(self._saved_page_states)
            for state in self._saved_page_states:
                self.__dict__.update(state)
                self.draw_page_number(num_pages)
                super().showPage()
            super().save()

        def draw_page_number(self, page_count):
            self.saveState()
            self.setFont("Helvetica", 8)
            self.setFillColor(colors.HexColor("#6B7280"))
            self.drawRightString(A4[0] - 36, 18, f"Page {self._pageNumber} of {page_count}")
            self.drawString(36, 18, "Generated by ExamSense — For every student, every exam.")
            self.setStrokeColor(colors.HexColor("#E5E7EB"))
            self.setLineWidth(0.5)
            self.line(36, 28, A4[0] - 36, 28)
            self.restoreState()


def clean_pdf_text(text: str) -> str:
    """Sanitizes text for ReportLab Paragraph XML parser."""
    if not text:
        return ""
    # Escape XML entities
    text = str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    # Allow safe bold/italic tags back
    text = text.replace("&lt;b&gt;", "<b>").replace("&lt;/b&gt;", "</b>")
    text = text.replace("&lt;i&gt;", "<i>").replace("&lt;/i&gt;", "</i>")
    return text.strip()


def generate_study_plan_pdf(
    subject_dict: Dict[str, Any],
    topics: List[Dict[str, Any]],
    repeated_questions: List[Dict[str, Any]],
    stats: Dict[str, Any],
    suggested_questions: Optional[List[Dict[str, Any]]] = None,
    sections: Optional[List[str]] = None,
) -> io.BytesIO:
    """
    Generates a professional, organized ExamSense Study Plan PDF.
    
    Sections supported via query param ?sections=summary,topics,repeated,questions,plan:
    1. Cover & Executive Summary (High/Medium/Low counts & Top 5 Topics)
    2. Prioritized Topic Matrix (grouped by High/Medium/Low)
    3. Verified Repeated Questions across cycles
    4. Important Questions (Past Papers + Notes Suggestions with checkboxes)
    5. 7-Day Study Action Plan
    """
    buffer = io.BytesIO()

    if not REPORTLAB_AVAILABLE:
        text = f"EXAMSENSE STUDY PLAN\nSubject: {subject_dict.get('name')} ({subject_dict.get('code')})\n"
        text += f"Date: {datetime.now().strftime('%Y-%m-%d')}\n\nTOPICS BY PRIORITY:\n"
        for t in topics:
            text += f"[{t.get('priority_level')}] {t.get('name')} - Score: {t.get('priority_score')}\n"
        buffer.write(text.encode("utf-8"))
        buffer.seek(0)
        return buffer

    # Active sections filter
    active_sections = set(sections) if sections else {"summary", "topics", "repeated", "questions", "plan"}

    doc = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=42,
    )

    styles = getSampleStyleSheet()

    # Typography & Styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#4F46E5"),
        spaceAfter=2,
    )
    subtitle_style = ParagraphStyle(
        "DocSubTitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#4B5563"),
        spaceAfter=10,
    )
    section_heading = ParagraphStyle(
        "SectionHeading",
        parent=styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#1E1B4B"),
        spaceBefore=12,
        spaceAfter=6,
    )
    sub_heading = ParagraphStyle(
        "SubHeading",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#374151"),
        spaceBefore=6,
        spaceAfter=4,
    )
    cell_style = ParagraphStyle(
        "CellNormal",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=11,
        textColor=colors.HexColor("#1F2937"),
    )
    cell_bold = ParagraphStyle(
        "CellBold",
        parent=cell_style,
        fontName="Helvetica-Bold",
    )

    story = []

    # -----------------------------------------------------------------------
    # 1. Header Banner & Cover
    # -----------------------------------------------------------------------
    story.append(Paragraph("ExamSense | AI Exam Intelligence", title_style))
    tagline = '<i>"Know what to study. Fast, transparent exam predictions."</i>'
    
    exam_level = clean_pdf_text(subject_dict.get("exam_type") or "General Exam")
    source_type = subject_dict.get("source") or ("demo" if subject_dict.get("is_demo") else "papers")
    source_badge = "Based on Uploaded Papers" if source_type == "papers" else ("AI Curriculum Estimate" if source_type == "ai_estimate" else "Sample Demo Data")
    
    meta_info = (
        f"<b>Subject:</b> {clean_pdf_text(subject_dict.get('name'))} ({clean_pdf_text(subject_dict.get('code'))}) &nbsp;|&nbsp; "
        f"<b>Level:</b> {exam_level} &nbsp;|&nbsp; "
        f"<b>Source:</b> {source_badge} &nbsp;|&nbsp; "
        f"<b>Generated:</b> {datetime.now().strftime('%d %B %Y')}"
    )
    story.append(Paragraph(f"{tagline}<br/>{meta_info}", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#6366F1"), spaceAfter=10))

    # -----------------------------------------------------------------------
    # 2. Executive Summary & Top 5 Topics (if "summary" in active_sections)
    # -----------------------------------------------------------------------
    if "summary" in active_sections:
        high_topics = [t for t in topics if t.get("priority_level") == "High"]
        med_topics = [t for t in topics if t.get("priority_level") == "Medium"]
        low_topics = [t for t in topics if t.get("priority_level") == "Low"]

        total_q = stats.get("total_questions", len(topics))
        total_papers = stats.get("total_papers", 1)

        summary_data = [
            [
                Paragraph("<b>Papers / Cycles</b>", cell_bold),
                Paragraph("<b>Total Questions</b>", cell_bold),
                Paragraph("<b>High Priority Topics</b>", cell_bold),
                Paragraph("<b>Medium Priority</b>", cell_bold),
                Paragraph("<b>Repeated Patterns</b>", cell_bold),
            ],
            [
                Paragraph(f"{total_papers} Exam Cycles", cell_style),
                Paragraph(f"{total_q} Questions", cell_style),
                Paragraph(f"<font color='#DC2626'><b>{len(high_topics)} Must-Study</b></font>", cell_style),
                Paragraph(f"{len(med_topics)} Topics", cell_style),
                Paragraph(f"{len(repeated_questions)} Recurring Groups", cell_style),
            ],
        ]
        summary_table = Table(summary_data, colWidths=[105, 105, 110, 100, 100])
        summary_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F9FAFB")),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#D1D5DB")),
            ("TOPPADDING", (0, 0), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ]))
        story.append(summary_table)
        story.append(Spacer(1, 8))

        # "Start Here" Quick Box with Top 5 High-Priority Topics
        top5 = topics[:5]
        if top5:
            top5_items = "<br/>".join([
                f"• <b>{clean_pdf_text(t.get('name'))}</b> — Score: {t.get('priority_score', 0)}/100 [{t.get('priority_level')}]"
                for t in top5
            ])
            top5_box_html = f"<b>🚀 Quick Start Focus (Top Predicted Topics):</b><br/>{top5_items}"
            top5_p = Paragraph(top5_box_html, cell_style)
            top5_table = Table([[top5_p]], colWidths=[520])
            top5_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#EEF2FF")),
                ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#818CF8")),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 10),
                ("RIGHTPADDING", (0, 0), (-1, -1), 10),
            ]))
            story.append(top5_table)
            story.append(Spacer(1, 10))

    # -----------------------------------------------------------------------
    # 3. Prioritized Topic Table (if "topics" in active_sections)
    # -----------------------------------------------------------------------
    if "topics" in active_sections and topics:
        story.append(Paragraph("1. Prioritized Topic Matrix", section_heading))

        topic_table_data = [
            [
                Paragraph("<b>Priority</b>", cell_bold),
                Paragraph("<b>Topic Name</b>", cell_bold),
                Paragraph("<b>Frequency</b>", cell_bold),
                Paragraph("<b>Total Marks</b>", cell_bold),
                Paragraph("<b>Years Asked</b>", cell_bold),
                Paragraph("<b>Score</b>", cell_bold),
            ]
        ]

        # Group by High, Medium, Low
        for group_label, group_topics, color_code in [
            ("High Priority", [t for t in topics if t.get("priority_level") == "High"], "#DC2626"),
            ("Medium Priority", [t for t in topics if t.get("priority_level") == "Medium"], "#D97706"),
            ("Low Priority", [t for t in topics if t.get("priority_level") == "Low"], "#059669"),
        ]:
            if not group_topics:
                continue

            for t in group_topics:
                years_list = t.get("years_asked", [])
                years_str = ", ".join(str(y) for y in years_list) if years_list else "Recent"
                freq_str = f"{t.get('frequency', 1)}x"

                topic_table_data.append([
                    Paragraph(f"<font color='{color_code}'><b>{t.get('priority_level')}</b></font>", cell_style),
                    Paragraph(clean_pdf_text(t.get("name")), cell_style),
                    Paragraph(freq_str, cell_style),
                    Paragraph(f"{t.get('total_marks', 0)}M", cell_style),
                    Paragraph(years_str, cell_style),
                    Paragraph(f"<b>{t.get('priority_score', 0)}/100</b>", cell_style),
                ])

        topic_table = Table(topic_table_data, colWidths=[65, 195, 65, 65, 75, 55], repeatRows=1)
        topic_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2FF")),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(topic_table)
        story.append(Spacer(1, 10))

    # -----------------------------------------------------------------------
    # 4. Repeated Questions (if "repeated" in active_sections and repeated_questions)
    # -----------------------------------------------------------------------
    if "repeated" in active_sections and repeated_questions:
        story.append(Paragraph("2. Verified Recurring & Repeated Questions (TF-IDF Match)", section_heading))
        story.append(Paragraph(
            "These questions appeared across multiple examination cycles with high semantic similarity. Master these first!",
            subtitle_style,
        ))

        rep_data = [
            [
                Paragraph("<b>#</b>", cell_bold),
                Paragraph("<b>Recurring Question Pattern</b>", cell_bold),
                Paragraph("<b>Years Appeared</b>", cell_bold),
                Paragraph("<b>Match</b>", cell_bold),
            ]
        ]

        for i, rq in enumerate(repeated_questions[:8]):
            years_str = ", ".join(str(y) for y in rq.get("years", []))
            rep_data.append([
                Paragraph(str(i + 1), cell_style),
                Paragraph(clean_pdf_text(rq.get("canonical_question", "")), cell_style),
                Paragraph(years_str, cell_style),
                Paragraph(f"{rq.get('similarity_score', 85)}%", cell_style),
            ])

        rep_table = Table(rep_data, colWidths=[25, 360, 75, 60], repeatRows=1)
        rep_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#FEF3C7")),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#FDE68A")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(rep_table)
        story.append(Spacer(1, 10))

    # -----------------------------------------------------------------------
    # 5. Important Questions (if "questions" in active_sections)
    # -----------------------------------------------------------------------
    combined_questions = []
    # From suggested_questions (notes or AI suggestions)
    if suggested_questions:
        for sq in suggested_questions:
            combined_questions.append({
                "topic": sq.get("topic_name") or "Key Topic",
                "text": sq.get("question_text", ""),
                "marks": sq.get("expected_marks", 5),
                "type": sq.get("question_type", "short answer"),
                "source_label": "Suggested from notes" if sq.get("source") == "notes" else "AI suggested",
            })

    if "questions" in active_sections and combined_questions:
        story.append(Paragraph("3. Important Practice Questions & Checklists", section_heading))
        story.append(Paragraph("Use these checkboxes as you practice questions.", subtitle_style))

        q_table_data = [
            [
                Paragraph("<b>Done</b>", cell_bold),
                Paragraph("<b>Topic</b>", cell_bold),
                Paragraph("<b>Question</b>", cell_bold),
                Paragraph("<b>Marks</b>", cell_bold),
                Paragraph("<b>Source</b>", cell_bold),
            ]
        ]

        for item in combined_questions[:15]:
            q_table_data.append([
                Paragraph("☐", cell_bold),
                Paragraph(clean_pdf_text(item["topic"]), cell_style),
                Paragraph(clean_pdf_text(item["text"]), cell_style),
                Paragraph(f"{item['marks']}M", cell_style),
                Paragraph(f"<font color='#4F46E5'>{clean_pdf_text(item['source_label'])}</font>", cell_style),
            ])

        q_table = Table(q_table_data, colWidths=[35, 110, 275, 45, 55], repeatRows=1)
        q_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F3F4F6")),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("ALIGN", (0, 1), (0, -1), "CENTER"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(q_table)
        story.append(Spacer(1, 10))

    # -----------------------------------------------------------------------
    # 6. 7-Day Study Action Plan (if "plan" in active_sections)
    # -----------------------------------------------------------------------
    if "plan" in active_sections and topics:
        story.append(Paragraph("4. 7-Day Targeted Revision Schedule", section_heading))
        story.append(Paragraph("Optimized schedule prioritizing highest impact topics first.", subtitle_style))

        high_names = [t.get("name") for t in topics if t.get("priority_level") == "High"]
        med_names = [t.get("name") for t in topics if t.get("priority_level") == "Medium"]
        low_names = [t.get("name") for t in topics if t.get("priority_level") == "Low"]

        def _get_items_slice(lst, start, count):
            chunk = lst[start:start + count]
            return ", ".join(chunk) if chunk else "Topic deep dive & practice problems"

        plan_data = [
            [
                Paragraph("<b>Day</b>", cell_bold),
                Paragraph("<b>Focus Areas</b>", cell_bold),
                Paragraph("<b>Target Topics</b>", cell_bold),
                Paragraph("<b>Action Items</b>", cell_bold),
            ],
            [
                Paragraph("Day 1", cell_bold),
                Paragraph("High Priority", cell_style),
                Paragraph(clean_pdf_text(_get_items_slice(high_names, 0, 2)), cell_style),
                Paragraph("Study core definitions, formulas, and diagrams.", cell_style),
            ],
            [
                Paragraph("Day 2", cell_bold),
                Paragraph("High Priority", cell_style),
                Paragraph(clean_pdf_text(_get_items_slice(high_names, 2, 2)), cell_style),
                Paragraph("Solve recurring questions and write out derivations.", cell_style),
            ],
            [
                Paragraph("Day 3", cell_bold),
                Paragraph("High Priority", cell_style),
                Paragraph(clean_pdf_text(_get_items_slice(high_names, 4, 2)), cell_style),
                Paragraph("Review difficult concepts and take 5-MCQ practice quiz.", cell_style),
            ],
            [
                Paragraph("Day 4", cell_bold),
                Paragraph("Medium Priority", cell_style),
                Paragraph(clean_pdf_text(_get_items_slice(med_names, 0, 2)), cell_style),
                Paragraph("Focus on differences and comparison tables.", cell_style),
            ],
            [
                Paragraph("Day 5", cell_bold),
                Paragraph("Medium Priority", cell_style),
                Paragraph(clean_pdf_text(_get_items_slice(med_names, 2, 2)), cell_style),
                Paragraph("Practice numerical problems and exam paper questions.", cell_style),
            ],
            [
                Paragraph("Day 6", cell_bold),
                Paragraph("Low & Notes", cell_style),
                Paragraph(clean_pdf_text(_get_items_slice(low_names, 0, 3)), cell_style),
                Paragraph("Skim secondary topics and review student notes.", cell_style),
            ],
            [
                Paragraph("Day 7", cell_bold),
                Paragraph("Full Mock & Review", cell_style),
                Paragraph("All Topics & Formula Sheet", cell_style),
                Paragraph("Timed mock exam, formula revision, and rest.", cell_style),
            ],
        ]

        plan_table = Table(plan_data, colWidths=[45, 95, 230, 150], repeatRows=1)
        plan_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#EEF2FF")),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#E5E7EB")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(plan_table)
        story.append(Spacer(1, 10))

    # Disclaimer Box
    disclaimer_html = (
        "<b>Academic Disclaimer:</b> This study plan is algorithmically generated based on past examination "
        "frequencies and mathematical trend analysis to optimize student revision efficiency. "
        "It does not constitute an official exam paper guarantee."
    )
    disclaimer_p = Paragraph(disclaimer_html, subtitle_style)
    disclaimer_box = Table([[disclaimer_p]], colWidths=[520])
    disclaimer_box.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#F9FAFB")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#D1D5DB")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(disclaimer_box)

    # Build Document with NumberedCanvas
    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer
